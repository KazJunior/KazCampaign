export const ALL_CLASS_MISSIONS: ClassMission[] = Object.values(CLASS_MISSIONS).flat();
export const ALL_CLASS_SKINS: ClassSkin[] = Object.values(CLASS_SKINS).flat();

const SKINS_BY_ID = new Map<string, ClassSkin>(ALL_CLASS_SKINS.map((s) => [s.id, s]));
const MISSIONS_BY_ID = new Map<string, ClassMission>(ALL_CLASS_MISSIONS.map((m) => [m.id, m]));

export function getClassMissions(className: string): ClassMission[] {
  return CLASS_MISSIONS[className] || [];
}

export function getClassSkins(className: string): ClassSkin[] {
  return CLASS_SKINS[className] || [];
}

export function getSkinById(skinId?: string | null): ClassSkin | undefined {
  if (!skinId) return undefined;
  return SKINS_BY_ID.get(skinId);
}

export function getMissionById(missionId?: string | null): ClassMission | undefined {
  if (!missionId) return undefined;
  return MISSIONS_BY_ID.get(missionId);
}

export function getEquippedSkin(className: string, equippedClassSkins?: Record<string, string>): ClassSkin {
  const activeSkinId = equippedClassSkins?.[className];
  if (activeSkinId) {
    const skin = SKINS_BY_ID.get(activeSkinId);
    if (skin && skin.className === className) return skin;
  }
  const defaultSkin = CLASS_SKINS[className]?.[0];
  return (
    defaultSkin || {
      id: `${className}_default`,
      className,
      name: 'Padrão',
      subtitle: 'Aparência Clássica',
      description: 'Aparência inicial padrão da classe.',
      rarity: 'common',
      color: '#4C8DFF',
      avatarKey: className,
      iconName: 'Shield',
      accentGlow: '#3B82F6',
      badge: 'PADRÃO',
      unlockedByDefault: true,
    }
  );
}

export function isSkinUnlocked(skinId: string, unlockedSkins?: string[]): boolean {
  const skin = SKINS_BY_ID.get(skinId);
  if (!skin) return false;
  if (skin.unlockedByDefault) return true;
  return Boolean(unlockedSkins?.includes(skinId));
}

export function isMissionCompleted(
  missionId: string,
  classMissionsProgress?: Record<string, { completedMissions: string[] }>
): boolean {
  const mission = MISSIONS_BY_ID.get(missionId);
  if (!mission) return false;
  const p = classMissionsProgress?.[mission.className];
  return Boolean(p?.completedMissions?.includes(missionId));
}

export function getMissionProgress(
  mission: ClassMission,
  classStats?: Record<string, number>
): { current: number; target: number; percent: number; isReadyToClaim: boolean } {
  const current = Math.min(mission.targetValue, classStats?.[mission.statKey] || 0);
  const target = mission.targetValue;
  const percent = Math.min(100, Math.round((current / target) * 100));
  const isReadyToClaim = current >= target;
  return { current, target, percent, isReadyToClaim };
}

export function incrementClassStat(
  currentProgress: PlayerProgress,
  className: string,
  statKey: 'damage_dealt' | 'kills' | 'skill_uses' | 'battles_won' | 'bosses_defeated',
  amount: number = 1
): PlayerProgress {
  if (!className || amount <= 0) return currentProgress;
  const canonical = className === 'engenheiro' ? 'druida' : className;
  const currentData = currentProgress.classMissionsProgress?.[canonical] || {
    completedMissions: [],
    stats: {},
  };
  const currentVal = currentData.stats[statKey] || 0;
  const updatedData = {
    ...currentData,
    stats: {
      ...currentData.stats,
      [statKey]: currentVal + amount,
    },
  };
  return {
    ...currentProgress,
    classMissionsProgress: {
      ...(currentProgress.classMissionsProgress || {}),
      [canonical]: updatedData,
    },
  };
}

export function incrementPartyStats(
  currentProgress: PlayerProgress,
  partyClasses: string[],
  statKey: 'damage_dealt' | 'kills' | 'skill_uses' | 'battles_won' | 'bosses_defeated',
  amount: number = 1
): PlayerProgress {
  let updated = currentProgress;
  for (const c of partyClasses) {
    updated = incrementClassStat(updated, c, statKey, amount);
  }
  return updated;
}

